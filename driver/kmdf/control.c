#include "iprcflt.h"

static const GUID IpInterface = IPRC_INTERFACE_GUID_INIT;
static const GUID IpRawClass = IPRC_RAW_CLASS_GUID_INIT;
static volatile LONG IpInstances;
static const UNICODE_STRING IpPolicyName = RTL_CONSTANT_STRING(L"IprcPolicyV1");

VOID IpLoadPolicy(WDFDEVICE device)
{
    WDFKEY key;
    IPRC_POLICY policy;
    ULONG bytes = 0, type = 0;
    NTSTATUS status = WdfDeviceOpenRegistryKey(device, PLUGPLAY_REGKEY_DEVICE, KEY_QUERY_VALUE,
        WDF_NO_OBJECT_ATTRIBUTES, &key);
    if (!NT_SUCCESS(status)) return;
    status = WdfRegistryQueryValue(key, &IpPolicyName, sizeof(policy), &policy, &bytes, &type);
    WdfRegistryClose(key);
    if (NT_SUCCESS(status) && type == REG_BINARY && bytes == sizeof(policy) && IpValidatePolicy(&policy))
        IpGetDevice(device)->Engine.Policy = policy;
}

NTSTATUS IpCreateControl(WDFDEVICE parent)
{
    PWDFDEVICE_INIT init = WdfPdoInitAllocate(parent);
    WDFDEVICE device;
    WDF_OBJECT_ATTRIBUTES attributes;
    WDF_IO_QUEUE_CONFIG queue;
    WCHAR number[32];
    UNICODE_STRING instance;
    DECLARE_CONST_UNICODE_STRING(id, L"IPRC1000\\Control");
    NTSTATUS status;
    if (!init) return STATUS_INSUFFICIENT_RESOURCES;
    WdfDeviceInitSetDeviceType(init, FILE_DEVICE_UNKNOWN);
    WdfDeviceInitSetCharacteristics(init, FILE_AUTOGENERATED_DEVICE_NAME | FILE_DEVICE_SECURE_OPEN, TRUE);
    WdfDeviceInitSetExclusive(init, TRUE);
    status = WdfPdoInitAssignRawDevice(init, &IpRawClass);
    if (!NT_SUCCESS(status)) goto failed;
    status = WdfDeviceInitAssignSDDLString(init, &SDDL_DEVOBJ_SYS_ALL_ADM_ALL);
    if (!NT_SUCCESS(status)) goto failed;
    status = WdfPdoInitAssignDeviceID(init, &id);
    if (!NT_SUCCESS(status)) goto failed;
    status = WdfPdoInitAddHardwareID(init, &id);
    if (!NT_SUCCESS(status)) goto failed;
    status = RtlStringCchPrintfW(number, RTL_NUMBER_OF(number), L"%lu", (ULONG)InterlockedIncrement(&IpInstances));
    if (!NT_SUCCESS(status)) goto failed;
    RtlInitUnicodeString(&instance, number);
    status = WdfPdoInitAssignInstanceID(init, &instance);
    if (!NT_SUCCESS(status)) goto failed;
    WDF_OBJECT_ATTRIBUTES_INIT_CONTEXT_TYPE(&attributes, IPRC_CONTROL_CONTEXT);
    status = WdfDeviceCreate(&init, &attributes, &device);
    if (!NT_SUCCESS(status)) goto failed;
    IpGetControl(device)->Parent = parent;
    status = WdfDeviceCreateDeviceInterface(device, &IpInterface, NULL);
    if (!NT_SUCCESS(status)) goto childFailed;
    WDF_IO_QUEUE_CONFIG_INIT_DEFAULT_QUEUE(&queue, WdfIoQueueDispatchSequential);
    queue.EvtIoDeviceControl = IpDeviceControl;
    WDF_OBJECT_ATTRIBUTES_INIT(&attributes);
    attributes.ExecutionLevel = WdfExecutionLevelPassive;
    status = WdfIoQueueCreate(device, &queue, &attributes, WDF_NO_HANDLE);
    if (!NT_SUCCESS(status)) goto childFailed;
    status = WdfFdoAddStaticChild(parent, device);
    if (!NT_SUCCESS(status)) goto childFailed;
    return status;
childFailed:
    WdfObjectDelete(device);
    return status;
failed:
    if (init) WdfDeviceInitFree(init);
    return status;
}

VOID IpDeviceControl(WDFQUEUE queue, WDFREQUEST request, size_t outputLength,
    size_t inputLength, ULONG code)
{
    WDFDEVICE parent = IpGetControl(WdfIoQueueGetDevice(queue))->Parent;
    IPRC_DEVICE_CONTEXT *ctx = IpGetDevice(parent);
    NTSTATUS status = STATUS_INVALID_DEVICE_REQUEST;
    size_t information = 0;
    UNREFERENCED_PARAMETER(outputLength);
    if (code == IPRC_IOCTL_STATUS) {
        IPRC_STATUS *out;
        status = WdfRequestRetrieveOutputBuffer(request, sizeof(*out), (PVOID *)&out, NULL);
        if (NT_SUCCESS(status)) {
            RtlZeroMemory(out, sizeof(*out));
            WdfSpinLockAcquire(ctx->Lock);
            out->Size = sizeof(*out); out->Version = IPRC_ABI_VERSION;
            out->Mode = ctx->Engine.Policy.Mode;
            out->Connected = ctx->Online && ctx->Upper.ClassService != NULL;
            out->QueueDepth = ctx->Engine.Count;
            out->LastPersistStatus = (uint32_t)ctx->LastPersistStatus;
            out->Accepted = ctx->Engine.Accepted; out->Delivered = ctx->Engine.Delivered;
            out->Suppressed = ctx->Engine.Suppressed; out->Repeats = ctx->Engine.Repeats;
            out->Backpressure = ctx->Engine.Backpressure;
            WdfSpinLockRelease(ctx->Lock);
            information = sizeof(*out);
        }
    } else if (code == IPRC_IOCTL_GET_POLICY) {
        IPRC_POLICY *out;
        status = WdfRequestRetrieveOutputBuffer(request, sizeof(*out), (PVOID *)&out, NULL);
        if (NT_SUCCESS(status)) {
            WdfSpinLockAcquire(ctx->Lock);
            *out = ctx->Engine.Policy;
            WdfSpinLockRelease(ctx->Lock);
            information = sizeof(*out);
        }
    } else if (code == IPRC_IOCTL_SET_POLICY) {
        IPRC_SET_POLICY *input;
        status = WdfRequestRetrieveInputBuffer(request, sizeof(*input), (PVOID *)&input, NULL);
        if (NT_SUCCESS(status)) {
            if (inputLength != sizeof(*input) || input->Persist > 1 || input->Reserved || !IpValidatePolicy(&input->Policy))
                status = STATUS_INVALID_PARAMETER;
            else {
                if (input->Persist) {
                    WDFKEY key;
                    status = WdfDeviceOpenRegistryKey(parent, PLUGPLAY_REGKEY_DEVICE, KEY_SET_VALUE,
                        WDF_NO_OBJECT_ATTRIBUTES, &key);
                    if (NT_SUCCESS(status)) {
                        status = WdfRegistryAssignValue(key, &IpPolicyName, REG_BINARY, sizeof(input->Policy), &input->Policy);
                        WdfRegistryClose(key);
                    }
                }
                WdfSpinLockAcquire(ctx->Lock);
                ctx->LastPersistStatus = status;
                if (NT_SUCCESS(status)) ctx->Engine.Policy = input->Policy;
                WdfSpinLockRelease(ctx->Lock);
            }
        }
    }
    WdfRequestCompleteWithInformation(request, status, information);
}
